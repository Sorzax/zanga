// Dependency-free packaging for this project's deliberately small ES-module subset.
// Editable sources stay separate. Browser output uses classic scripts so a user
// can open index.html directly, including course loading, without file:// fetches.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { META, ORDER, THEMES, SUBJECT_STATS } from '../data/catalog.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');
const version = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8')).version;
const files = [
  'data/catalog.js',
  'assets/js/core/utils.js', 'assets/js/core/events.js', 'assets/js/core/storage.js',
  'assets/js/core/state.js', 'assets/js/core/effects.js', 'assets/js/core/rewards.js',
  'assets/js/core/helpers.js', 'assets/js/ui/theme.js',
  'assets/js/features/quiz.js', 'assets/js/features/plan.js',
  'assets/js/features/lessons.js', 'assets/js/features/chapter-test.js',
  'assets/js/features/builder.js', 'assets/js/features/extra.js',
  'assets/js/features/mistakes.js', 'assets/js/features/summary.js',
  'assets/js/features/drills.js', 'assets/js/ui/home.js', 'assets/js/ui/navigation.js'
];

const importPattern = /^import\s*\{([^}]+)\}\s*from\s*['"]([^'"]+)['"];?\s*$/gm;
function stripModuleSyntax(source) {
  const output = source.replace(importPattern, '')
    .replace(/^export\s*\{[^}]*\};?\s*$/gm, '')
    .replace(/^export\s+(?=(?:const|let|function|async\s+function)\b)/gm, '');
  if (/^\s*(?:import|export)\s/m.test(output)) throw new Error('Unsupported module declaration; update the build script explicitly.');
  return output.trim();
}
const outputs = new Map();
const sharedNames = new Set();
for (const key of ORDER) {
  const data = await readFile(resolve(root, `data/subjects/${key}.js`), 'utf8');
  const source = await readFile(resolve(root, `assets/js/subjects/${key}.js`), 'utf8');
  const names = new Set();
  for (const match of source.matchAll(importPattern)) {
    if (match[2].includes('/data/subjects/')) continue;
    for (const binding of match[1].split(',').map(value => value.trim()).filter(Boolean)) {
      if (!/^[A-Za-z_$][\w$]*$/.test(binding)) throw new Error(`Unsupported import binding: ${binding}`);
      names.add(binding);
      sharedNames.add(binding);
    }
  }
  const output = `/* Generated by npm run build. Edit data/subjects/${key}.js and assets/js/subjects/${key}.js. */\n` +
    `(function () {\n'use strict';\nglobalThis.ZangaChunks.register('${key}', function (shared) {\n` +
    `const { ${[...names].sort().join(', ')} } = shared;\n` + stripModuleSyntax(data) + '\n\n' +
    stripModuleSyntax(source) + '\nreturn { createSubject };\n});\n})();\n';
  outputs.set(`assets/js/runtime/${key}.js`, output);
}
const chunks = Object.fromEntries(ORDER.map(key => [key, createHash('sha256').update(outputs.get(`assets/js/runtime/${key}.js`)).digest('hex').slice(0, 12)]));

let core = '';
for (const file of files) {
  let source = stripModuleSyntax(await readFile(resolve(root, file), 'utf8'));
  if (file.endsWith('/navigation.js')) {
    source = source.replace(/import\(['"]\.\.\/subjects\/([a-z]+)\.js['"]\)/g, (_, key) => `loadSubjectChunk('${key}')`);
  }
  if (/\bimport\s*\(/.test(source)) throw new Error(`Unconverted dynamic import in ${file}`);
  core += `\n/* Source: ${file} */\n${source}\n`;
}

const runtime = `/* Generated browser entry ${version}. Source files remain in assets/js and data. */
(function () {
'use strict';
const entryUrl = document.currentScript.src;
const moduleRegistry = new Map();
const pendingChunks = new Map();
const chunkVersions = ${JSON.stringify(chunks)};
function loadSubjectChunk(key) {
  if (moduleRegistry.has(key)) return Promise.resolve(moduleRegistry.get(key));
  if (pendingChunks.has(key)) return pendingChunks.get(key);
  if (!Object.hasOwn(chunkVersions, key)) return Promise.reject(new Error('Unknown subject'));
  const pending = new Promise((resolveModule, rejectModule) => {
    const script = document.createElement('script');
    script.async = true;
    script.src = new URL(key + '.js?v=' + chunkVersions[key], entryUrl).href;
    script.onload = () => {
      if (moduleRegistry.has(key)) resolveModule(moduleRegistry.get(key));
      else rejectModule(new Error('Subject script did not register'));
    };
    script.onerror = () => rejectModule(new Error('Subject script could not load'));
    document.head.appendChild(script);
  });
  pendingChunks.set(key, pending);
  pending.then(() => pendingChunks.delete(key), () => pendingChunks.delete(key));
  return pending;
}
${core}
const shared = { ${[...sharedNames].sort().join(', ')} };
globalThis.ZangaChunks = Object.freeze({ register(key, setup) {
  if (!Object.hasOwn(chunkVersions, key) || moduleRegistry.has(key)) return;
  moduleRegistry.set(key, setup(shared));
} });
${stripModuleSyntax(await readFile(resolve(root, 'assets/js/main.js'), 'utf8'))}
})();
`;
outputs.set('assets/js/runtime/app.js', runtime);

// Materialize a nonempty home screen in HTML before JavaScript starts.
const escape = value => String(value).replace(/[&<>"']/g, c => ({ '&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;' }[c]));
const cards = ORDER.map(key => `<button class="scard" data-s="${key}" style="--c:${THEMES[key].rayeq.score}">
<svg viewBox="0 0 58 58" aria-hidden="true" fill="none" stroke="currentColor" stroke-width="2.4"><rect x="10" y="10" width="38" height="38" rx="8"/><path d="M18 21h22M18 29h22M18 37h14"/></svg>
<h2>${escape(META[key].name)}</h2><div class="sen">${escape(META[key].en)}</div>
<div class="smeta"><span>${SUBJECT_STATS[key].lessons} درس</span><span>${SUBJECT_STATS[key].questions} سؤال</span><span>${escape(META[key].sub)}</span></div>
<div class="sbar"><i></i></div></button>`).join('\n');
const template = await readFile(resolve(root, 'index.template.html'), 'utf8');
const appHash = createHash('sha256').update(runtime).digest('hex').slice(0, 12);
outputs.set('index.html', template.replace('{{SUBJECT_CARDS}}', cards).replace('{{APP_HASH}}', appHash));

const manifest = { version, outputs: Object.fromEntries([...outputs].map(([file, source]) => [file, createHash('sha256').update(source).digest('hex')])) };
outputs.set('assets/js/runtime/manifest.json', JSON.stringify(manifest, null, 2) + '\n');
let stale = false;
for (const [file, source] of outputs) {
  const path = resolve(root, file);
  if (checkOnly) {
    let current;
    try { current = await readFile(path, 'utf8'); } catch {}
    if (current !== source) { console.error(`Generated output needs rebuilding: ${relative(root, path)}`); stale = true; }
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, source);
  }
}
if (stale) { console.error('Run npm run build before uploading the project.'); process.exitCode = 1; }
else console.log(checkOnly ? 'Browser files match the editable source.' : `Built classic entry and ${ORDER.length} course scripts; index.html opens directly.`);
